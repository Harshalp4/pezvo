const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict'), ts = require('typescript');
const code = ts.transpileModule(fs.readFileSync('src/lib/business-enquiry.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const box = { exports: {} };
vm.runInNewContext(code, box);
const { validateBusinessEnquiry: validate, businessEnquiryMessage: message, normalizeEnquiryPhone: phone } = box.exports;
const valid = { type: 'Commercial care', name: 'Test Contact', phone: '+91 90000 00000', company: 'Test Hotel & Spa', email: 'enquiry@example.test', service: 'Linen & towels', area: 'Nerul, Navi Mumbai', requirements: '100 towels / week\nPickup: Monday & Thursday. Budget: ₹5,000.' };
assert.equal(Object.keys(validate(valid)).length, 0);
assert.equal(phone(valid.phone), '9000000000');
assert.equal(phone('90000 00000'), '9000000000');
assert.ok(validate({ ...valid, phone: '+44 7700 900123' }).phone);
assert.ok(validate({ ...valid, phone: '900000000' }).phone);
assert.ok(validate({ ...valid, company: '   ' }).company);
assert.equal(Object.keys(validate({ ...valid, type: 'Bulk order', company: '', email: '' })).length, 0);
assert.ok(validate({ ...valid, email: 'not an email' }).email);
assert.ok(validate({ ...valid, service: 'Invalid service' }).service);
assert.ok(validate({ ...valid, requirements: ' '.repeat(10) }).requirements);
assert.ok(validate({ ...valid, requirements: 'a'.repeat(1501) }).requirements);
assert.ok(validate({ ...valid, area: 'a'.repeat(161) }).area);
for (const field of ['name', 'phone', 'area', 'service', 'requirements']) assert.ok(validate({ ...valid, [field]: '' })[field]);
const draft = message(valid);
for (const value of [valid.company, valid.email, valid.area, valid.service, valid.requirements, '+91 9000000000']) assert.ok(draft.includes(value), value);
assert.equal(new URL('https://wa.me/918828676480?text=' + encodeURIComponent(draft)).searchParams.get('text'), draft);
const minimal = message({ ...valid, type: 'Bulk order', company: '', email: '' });
assert.match(minimal, /bulk order enquiry/);
assert.doesNotMatch(minimal, /Business \/ organisation:|Email:/);
console.log('PASS commercial enquiry: required fields, optional bulk organisation, phone normalization, invalid email/service, size limits and complete WhatsApp draft encoding. No messages sent.');
